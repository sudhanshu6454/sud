      local v pairs=() set_names=() name label
      for name in META_APP_SECRET META_VERIFY_TOKEN META_SYSTEM_USER_TOKEN; do
        case "$name" in
          META_APP_SECRET) label="the Meta app's App Secret (App settings > Basic)" ;;
          META_VERIFY_TOKEN) label="a verify token you make up (16+ letters or digits; you type the same string into Meta's dashboard in the webhook step; it is never shown)" ;;
